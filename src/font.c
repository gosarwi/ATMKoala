/* ── Поиск глифа по codepoint ─────────────────────────────── */
const uint8_t *font_get_glyph(uint32_t cp) {
    /* ASCII */
    if (cp >= 0x20 && cp <= 0x7E)
        return ascii_glyphs[cp - 0x20];
    /* Ё */
    if (cp == 0x0401) return cyrillic_glyphs[64];
    /* ё */
    if (cp == 0x0451) return cyrillic_glyphs[65];
    /* Кириллица А-Я (U+0410-U+042F) */
    if (cp >= 0x0410 && cp <= 0x042F)
        return cyrillic_glyphs[cp - 0x0410];
    /* а-я (U+0430-U+044F) */
    if (cp >= 0x0430 && cp <= 0x044F)
        return cyrillic_glyphs[32 + (cp - 0x0430)];
    /* Псевдографика и спецсимволы */
    for (int i = 0; i < BOX_COUNT; i++)
        if (box_g[i].cp == cp) return box_g[i].g;
    /* Старые эмодзи */
    for (int i = 0; i < EMOJI_COUNT; i++)
        if (emoji_codepoints[i] == cp) return emoji_glyphs[i];
    /* Неизвестный */
    return glyph_unknown;
}
