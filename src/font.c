/* ── UTF-8 декодер ───────────────────────────────────────── */
uint32_t utf8_decode(const uint8_t **ptr) {
    const uint8_t *p = *ptr;
    uint32_t cp;
    if ((*p & 0x80) == 0) {
        cp = *p++; 
    } else if ((*p & 0xE0) == 0xC0) {
        cp  = (*p++ & 0x1F) << 6;
        cp |= (*p++ & 0x3F);
    } else if ((*p & 0xF0) == 0xE0) {
        cp  = (*p++ & 0x0F) << 12;
        cp |= (*p++ & 0x3F) << 6;
        cp |= (*p++ & 0x3F);
    } else if ((*p & 0xF8) == 0xF0) {
        cp  = (*p++ & 0x07) << 18;
        cp |= (*p++ & 0x3F) << 12;
        cp |= (*p++ & 0x3F) << 6;
        cp |= (*p++ & 0x3F);
    } else {
        cp = '?'; p++;
    }
    *ptr = p;
    return cp;
}

int utf8_strlen(const char *s) {
    int n = 0;
    const uint8_t *p = (const uint8_t *)s;
    while (*p) { utf8_decode(&p); n++; }
    return n;
}


